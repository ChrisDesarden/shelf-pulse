export function translateCategory(category: string, locale: Locale): string {
  if (locale === 'en') return category;
  if (category === 'All') return 'Todos';
  return DEFAULT_CATEGORY_TRANSLATIONS_ES[category] || category;
}

export function translateUnit(unit: string | undefined, locale: Locale): string {
  if (!unit) return locale === 'es' ? 'Unidades' : 'Units';
  if (locale === 'en') return unit;
  return DEFAULT_UNIT_TRANSLATIONS_ES[unit] || unit;
}

export function translateProductName(name: string, locale: Locale): string {
  if (locale === 'en') return name;
  return DEFAULT_PRODUCT_NAME_TRANSLATIONS_ES[name] || name;
}

export function translateBarcodeLabel(label: string, locale: Locale): string {
  if (locale === 'en') return label;
  const map: Record<string, string> = {
    Barcode: 'Código de Barras',
    'UPC-E (8-Digit)': 'UPC-E (8 Dígitos)',
    'UPC-E / Short (6-Digit)': 'UPC-E / Corto (6 Dígitos)',
    'UPC-E (7-Digit -> 8-Digit)': 'UPC-E (7 -> 8 Dígitos)',
    'EAN-8 (8-Digit)': 'EAN-8 (8 Dígitos)',
    'UPC-A (12-Digit)': 'UPC-A (12 Dígitos)',
    'EAN-13 (13-Digit)': 'EAN-13 (13 Dígitos)',
    'GTIN-14 (14-Digit)': 'GTIN-14 (14 Dígitos)',
  };
  if (map[label]) return map[label];
  return label
    .replace(/Short UPC \((\d+)-Digit\)/, 'UPC Corto ($1 Dígitos)')
    .replace(/Code 128 \((\d+)-Char\)/, 'Código 128 ($1 Car.)');
}

